from config.constants import (
    ALERTPUSH_APP_ID_ENV,
    ALERTPUSH_APP_SECRET_ENV,
    FEISHU_ALARM_RECEIVE_ID_ENV,
    FEISHU_ALARM_RECEIVE_ID_TYPE_ENV,
    FEISHU_APP_ID_ENV,
    FEISHU_APP_SECRET_ENV,
    FEISHU_AUTHORIZATION_ERROR_CODES,
    FEISHU_CHAT_RECEIVE_ID_ENV,
    FEISHU_CHAT_RECEIVE_ID_TYPE_ENV,
    FEISHU_RATE_LIMIT_ERROR_CODES,
    FEISHU_VALIDATION_ERROR_CODES,
)


def test_feishu_env_names():
    assert FEISHU_APP_ID_ENV == "FEISHU_APP_ID"
    assert FEISHU_APP_SECRET_ENV == "FEISHU_APP_SECRET"
    assert FEISHU_CHAT_RECEIVE_ID_ENV == "FEISHU_CHAT_RECEIVE_ID"
    assert FEISHU_CHAT_RECEIVE_ID_TYPE_ENV == "FEISHU_CHAT_RECEIVE_ID_TYPE"
    assert ALERTPUSH_APP_ID_ENV == "ALERTPUSH_APP_ID"
    assert ALERTPUSH_APP_SECRET_ENV == "ALERTPUSH_APP_SECRET"
    assert FEISHU_ALARM_RECEIVE_ID_ENV == "FEISHU_ALARM_RECEIVE_ID"
    assert FEISHU_ALARM_RECEIVE_ID_TYPE_ENV == "FEISHU_ALARM_RECEIVE_ID_TYPE"


def test_feishu_delivery_error_code_allowlists_are_fixed() -> None:
    assert frozenset({230020, 99991400}) == FEISHU_RATE_LIMIT_ERROR_CODES
    assert frozenset({11310, 200860, 230001, 230025}) == FEISHU_VALIDATION_ERROR_CODES
    assert (
        frozenset({230002, 230006, 230013, 230017, 230018, 230027})
        == FEISHU_AUTHORIZATION_ERROR_CODES
    )
